/* eslint-disable @typescript-eslint/no-require-imports */
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const ts = require("../node_modules/typescript");

const projectRoot = path.resolve(__dirname, "..");
const sources = {
  shared: "src/lib/mock-data.ts",
  landing: "src/lib/landing-data.ts",
  nonprofit_admin: "src/lib/nonprofit-admin-data.ts",
  community_admin: "src/lib/community-admin-data.ts",
};

function loadSerializableExports(relativePath) {
  const source = fs.readFileSync(path.join(projectRoot, relativePath), "utf8");
  const compiled = ts.transpileModule(source, {
    compilerOptions: {
      target: ts.ScriptTarget.ES2020,
      module: ts.ModuleKind.CommonJS,
      esModuleInterop: true,
    },
  }).outputText;
  const compiledModule = { exports: {} };
  vm.runInNewContext(compiled, { module: compiledModule, exports: compiledModule.exports, require }, { filename: relativePath });
  return Object.fromEntries(
    Object.entries(compiledModule.exports).filter(([, value]) => typeof value !== "function")
  );
}

function sqlJson(value) {
  return `$dataset$${JSON.stringify(value)}$dataset$::jsonb`;
}

const rows = Object.entries(sources).map(([key, source]) => ({
  key,
  source,
  value: loadSerializableExports(source),
}));

const shared = rows.find((row) => row.key === "shared")?.value;
if (shared?.campaignCommunitiesByCampaign) {
  shared.campaignCommunitiesByCampaign = Object.fromEntries(
    Object.entries(shared.campaignCommunitiesByCampaign).map(([id, communities]) => [
      `c${id.repeat(7)}-${id.repeat(4)}-${id.repeat(4)}-${id.repeat(4)}-${id.repeat(12)}`,
      communities,
    ])
  );
}

const values = rows
  .map(({ key, source, value }) => `  ('${key}', '${source}', ${sqlJson(value)})`)
  .join(",\n");

const migration = `-- Generated by scripts/generate-site-datasets.cjs from the former UI fixture modules.
-- The table is public-read, service-role-write. Browser clients cannot change datasets.
create table if not exists public.site_datasets (
  key text primary key,
  source_file text not null,
  value jsonb not null,
  updated_at timestamptz not null default now()
);

alter table public.site_datasets enable row level security;

drop policy if exists "site_datasets_public_read" on public.site_datasets;
create policy "site_datasets_public_read" on public.site_datasets
  for select using (true);

insert into public.site_datasets (key, source_file, value)
values
${values}
on conflict (key) do update set
  source_file = excluded.source_file,
  value = excluded.value,
  updated_at = now();
`;

const output = path.join(projectRoot, "supabase/migrations/20260823150000_site_datasets.sql");
fs.writeFileSync(output, migration);
console.log(`Wrote ${path.relative(projectRoot, output)} with ${rows.length} datasets.`);
